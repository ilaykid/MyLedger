/**
 * Windows Task Scheduler integration.
 *
 *   npm run schedule:status     what is registered
 *   npm run schedule:check      validate the registrations without applying them
 *   npm run schedule:install    register both tasks (asks nothing, changes your system)
 *   npm run schedule:remove     unregister them
 *
 * Add a bare word to narrow either command to one task:
 *
 *   npm run schedule:install -- sync    only the daily sync
 *   npm run schedule:install -- api     only the dashboard
 *   npm run schedule:install -- 08:30   the sync at a different time
 *
 * TWO TASKS, because the system has two halves that fail differently:
 *
 * - SYNC (daily) scrapes, sends the digest, and takes a backup. If the machine
 *   is off it simply runs late, and the per-provider interval absorbs that.
 * - DASHBOARD (at logon) keeps the API up. Without it, looking at your own
 *   finances starts with opening a terminal - which is the kind of friction
 *   that quietly ends with nobody looking.
 *
 * Both register under the CURRENT user, so no elevation is needed and they
 * inherit your Windows account - which matters more than it looks: credentials
 * are sealed with DPAPI against *your* account, so a task running as SYSTEM or
 * another user could not decrypt them.
 */
import { execFile } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';

const run = promisify(execFile);

const SYNC_TASK = 'MyLedger daily sync';
const API_TASK = 'MyLedger dashboard';

const RUNTIME_DATA = process.env.LOCALAPPDATA ? path.join(process.env.LOCALAPPDATA, 'MyLedger', 'data') : '';
const DEPLOYED = !!RUNTIME_DATA && existsSync(path.join(RUNTIME_DATA, 'api.cmd'));
const NIGHTLY_RUNNER = DEPLOYED
  ? path.join(RUNTIME_DATA, 'nightly.cmd')
  : path.resolve(process.cwd(), 'scripts', 'nightly.cmd');
const API_RUNNER = DEPLOYED
  ? path.join(RUNTIME_DATA, 'api.cmd')
  : path.resolve(process.cwd(), 'scripts', 'api.cmd');
/**
 * Task Scheduler runs a .cmd in a visible console window, and a server that
 * lives for the whole session would leave one sitting on the desktop forever.
 * wscript with a window mode of 0 is the one launcher Windows ships that starts
 * something genuinely hidden without a helper binary.
 */
const API_LAUNCHER = DEPLOYED
  ? path.join(RUNTIME_DATA, 'api-hidden.vbs')
  : path.resolve(process.cwd(), 'scripts', 'api-hidden.vbs');

/**
 * A civilised hour. Scraping at dawn buys nothing - the previous day's
 * transactions have long settled - and a digest that arrives at 05:30 is read
 * at 10:00 anyway, by which point it has been pushed down the notification list.
 */
const DEFAULT_TIME = '10:00';

/**
 * .cmd wrappers rather than long schtasks argument strings: quoting a chained
 * command through schtasks is brittle, and a file is far easier to inspect and
 * edit later. It also gives us somewhere to write a log.
 */
function writeNightlyRunner(projectDir: string): void {
  const cmd = [
    '@echo off',
    'REM Generated by "npm run schedule:install" - safe to edit.',
    `cd /d "${projectDir}"`,
    'call npm run logs:rotate > nul 2>&1',
    'echo ================================================== >> nightly.log',
    'echo %DATE% %TIME% starting >> nightly.log',
    'call npm run scrape >> nightly.log 2>&1',
    'REM Back up AFTER the scrape, so the archive contains the day just recorded.',
    'REM Skipped silently until "npm run backup -- init" has chosen a destination.',
    'if exist backup.config.json call npm run backup >> nightly.log 2>&1',
    'REM Telegram is optional and never gets a chance to block the backup.',
    'call npm run notify >> nightly.log 2>&1',
    'echo %DATE% %TIME% finished >> nightly.log',
    '',
  ].join('\r\n');
  writeFileSync(NIGHTLY_RUNNER, cmd, 'utf-8');
}

/**
 * The dashboard supervisor. A logon task fires once, so anything that ends the
 * process - a crash, a Node upgrade, closing the window - would leave the
 * dashboard dead until the next logon. The loop restarts it; exit code 3 (port
 * already bound) is the one case where standing down is correct, otherwise a
 * manually started server and this one would fight over the port forever.
 */
function writeApiRunner(projectDir: string): void {
  const cmd = [
    '@echo off',
    'REM Generated by "npm run schedule:install" - safe to edit.',
    `cd /d "${projectDir}"`,
    'call npm run logs:rotate > nul 2>&1',
    ':loop',
    'echo %DATE% %TIME% starting api >> api.log',
    'call npm run api >> api.log 2>&1',
    'if "%ERRORLEVEL%"=="3" goto standdown',
    'echo %DATE% %TIME% api exited with %ERRORLEVEL% - restarting in 30s >> api.log',
    'timeout /t 30 /nobreak > nul',
    'goto loop',
    ':standdown',
    'echo %DATE% %TIME% port already in use - another instance owns it >> api.log',
    '',
  ].join('\r\n');
  writeFileSync(API_RUNNER, cmd, 'utf-8');

  // Run(command, 0 = hidden, False = do not wait).
  const vbs = [
    "' Generated by \"npm run schedule:install\" - starts the dashboard with no console window.",
    `CreateObject("WScript.Shell").Run """${API_RUNNER}""", 0, False`,
    '',
  ].join('\r\n');
  writeFileSync(API_LAUNCHER, vbs, 'utf-8');
}

/**
 * Task registration goes through the ScheduledTasks PowerShell module rather
 * than schtasks.exe, for one reason: schtasks takes the whole action as a
 * single /TR string, so a program plus an argument has to survive two layers of
 * quoting (Node's, then schtasks'). `wscript.exe "...\api-hidden.vbs"` is
 * exactly the shape that mangles, and a mangled task fails at logon - not here,
 * where anyone would notice. New-ScheduledTaskAction takes -Execute and
 * -Argument as separate parameters, so there is no command line to parse.
 *
 * It also reaches settings schtasks cannot: StartWhenAvailable is what makes a
 * missed 10:00 run when the machine wakes up instead of being skipped, which is
 * the single biggest hole in a laptop-hosted daily job.
 */
function psQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

async function powershell(script: string): Promise<string> {
  const { stdout } = await run('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script], {
    windowsHide: true,
  });
  return stdout;
}

/** True when the failure is Windows refusing an unelevated caller. */
function isAccessDenied(err: unknown): boolean {
  return /access is denied|UnauthorizedAccess|0x80070005/i.test(
    err instanceof Error ? err.message : String(err),
  );
}

async function query(taskName: string): Promise<string | null> {
  try {
    const { stdout } = await run('schtasks', ['/Query', '/TN', taskName, '/FO', 'LIST']);
    return stdout;
  } catch {
    return null;
  }
}

function field(info: string, label: string): string {
  return (
    info
      .split('\n')
      .find((l) => l.trim().startsWith(label))
      ?.split(':')
      .slice(1)
      .join(':')
      .trim() ?? '?'
  );
}

async function reportTask(taskName: string, logFile: string): Promise<void> {
  const info = await query(taskName);
  if (!info) {
    console.log(`\n${taskName}\n  not registered`);
    return;
  }
  console.log(`\n${taskName}`);
  console.log(`  Status:      ${field(info, 'Status')}`);
  console.log(`  Next run:    ${field(info, 'Next Run Time')}`);
  console.log(`  Last run:    ${field(info, 'Last Run Time')}`);
  console.log(`  Last result: ${field(info, 'Last Result')}`);
  console.log(`  Runs as:     ${field(info, 'Run As User')}`);
  console.log(`  Log:         ${DEPLOYED ? path.join(RUNTIME_DATA, logFile) : path.resolve(process.cwd(), logFile)}`);
}

async function status(which: Which): Promise<void> {
  if (which !== 'api') await reportTask(SYNC_TASK, 'nightly.log');
  if (which !== 'sync') await reportTask(API_TASK, 'api.log');

  const anyRegistered = (await query(SYNC_TASK)) ?? (await query(API_TASK));
  if (!anyRegistered) console.log('\nRegister them with:  npm run schedule:install');
}

interface TaskSpec {
  name: string;
  execute: string;
  argument: string;
  /** PowerShell fragment producing the trigger */
  trigger: string;
  /** PowerShell fragment producing the settings */
  settings: string;
}

/**
 * The three object-building statements, shared by the real registration and the
 * dry run. One line, so they need explicit `;` separators - joined by
 * whitespace they form a single unparseable statement, and PowerShell reports
 * that as a generic failure instead of pointing at the seam.
 */
function buildScript(spec: TaskSpec): string {
  return [
    `$action = New-ScheduledTaskAction -Execute ${psQuote(spec.execute)} ` +
      `-Argument ${psQuote(spec.argument)} -WorkingDirectory ${psQuote(DEPLOYED ? RUNTIME_DATA : process.cwd())}`,
    `$trigger = ${spec.trigger}`,
    `$settings = ${spec.settings}`,
  ].join('; ');
}

function registerScript(spec: TaskSpec): string {
  return (
    `${buildScript(spec)}; Register-ScheduledTask -TaskName ${psQuote(spec.name)} ` +
    '-Action $action -Trigger $trigger -Settings $settings -Force | Out-Null'
  );
}

/**
 * Register-ScheduledTask has no -WhatIf, so the dry run stops one statement
 * short and reads back what the cmdlets actually bound. That is where the risk
 * lives anyway: if a path or an argument were mangled by quoting, it shows up
 * here as a wrong Execute/Arguments pair rather than as a task that fails to
 * start weeks later.
 */
function previewScript(spec: TaskSpec): string {
  return (
    `${buildScript(spec)}; ` +
    '"exec={0}|args={1}|dir={2}|trigger={3}|restart={4}" -f $action.Execute, $action.Arguments, ' +
    '$action.WorkingDirectory, $trigger.CimClass.CimClassName, $settings.StartWhenAvailable'
  );
}

async function create(spec: TaskSpec): Promise<boolean> {
  if (await query(spec.name)) console.log(`  "${spec.name}" already exists - replacing it.`);
  try {
    await powershell(registerScript(spec));
    return true;
  } catch (err) {
    if (isAccessDenied(err)) {
      console.error(
        `\n  Windows refused to register "${spec.name}": access denied.\n` +
          '  Registering a scheduled task needs an elevated terminal on this machine.\n' +
          '  Open PowerShell or Terminal with "Run as administrator", cd here, and run\n' +
          '  this command again. The task still RUNS as you, so DPAPI keeps working.',
      );
    } else {
      console.error(
        `  Could not register "${spec.name}": ${err instanceof Error ? err.message.split('\n')[0] : err}`,
      );
    }
    return false;
  }
}

function syncSpec(time: string): TaskSpec {
  return {
    name: SYNC_TASK,
    execute: 'cmd.exe',
    argument: `/c "${NIGHTLY_RUNNER}"`,
    trigger: `New-ScheduledTaskTrigger -Daily -At ${psQuote(time)}`,
    // StartWhenAvailable is the important one: without it a machine that was
    // off at 10:00 simply skips that day, and the gap compounds because the
    // bank interval is ~weekly to begin with.
    settings:
      'New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries ' +
      '-DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew ' +
      '-ExecutionTimeLimit (New-TimeSpan -Hours 2)',
  };
}

function apiSpec(): TaskSpec {
  return {
    name: API_TASK,
    execute: 'wscript.exe',
    argument: `"${API_LAUNCHER}"`,
    trigger: `New-ScheduledTaskTrigger -AtLogOn -User ${psQuote(process.env.USERNAME ?? '')}`,
    // A dashboard is meant to outlive the day, so the default three-day
    // execution limit - which would silently kill it - has to go.
    settings:
      'New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries ' +
      '-MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero)',
  };
}

/** Validate both registrations without touching the system. */
async function dryRun(which: Which): Promise<void> {
  const time = process.argv.find((a) => /^\d{2}:\d{2}$/.test(a)) ?? DEFAULT_TIME;
  const specs = [
    ...(which !== 'api' ? [syncSpec(time)] : []),
    ...(which !== 'sync' ? [apiSpec()] : []),
  ];
  for (const spec of specs) {
    try {
      const out = (await powershell(previewScript(spec))).trim();
      const bound = Object.fromEntries(out.split('|').map((p) => p.split(/=(.*)/s).slice(0, 2)));
      const intact = bound.exec === spec.execute && bound.args === spec.argument;
      console.log(`${intact ? '✓' : '✗'} "${spec.name}"`);
      console.log(`    runs:    ${bound.exec} ${bound.args}`);
      console.log(`    in:      ${bound.dir}`);
      console.log(`    trigger: ${bound.trigger}`);
      if (!intact) {
        console.error('    the action was altered on the way in - do not install this');
        process.exitCode = 1;
      }
      if (!existsSync(spec.execute) && !/^[a-z]+\.exe$/i.test(spec.execute)) {
        console.error(`    ${spec.execute} does not exist`);
        process.exitCode = 1;
      }
    } catch (err) {
      console.error(`✗ "${spec.name}": ${err instanceof Error ? err.message.split('\n')[0] : err}`);
      process.exitCode = 1;
    }
  }
}

async function install(which: Which): Promise<void> {
  const projectDir = process.cwd();
  const time = process.argv.find((a) => /^\d{2}:\d{2}$/.test(a)) ?? DEFAULT_TIME;
  let ok = true;

  if (which !== 'api') {
    if (!existsSync(path.join(projectDir, 'accounts.config.json'))) {
      console.error('No accounts.config.json - configure an account before scheduling the sync.');
      process.exitCode = 1;
      return;
    }
    if (!DEPLOYED) writeNightlyRunner(projectDir);
    console.log(`${DEPLOYED ? 'Using protected runner' : 'Wrote'} ${NIGHTLY_RUNNER}`);
    ok = (await create(syncSpec(time))) && ok;
    if (ok) {
      console.log(`\n✓ "${SYNC_TASK}" runs daily at ${time}, as ${process.env.USERNAME}.`);
      console.log('  Scrapes, sends the digest for the day, then backs up.');
      console.log('  A day the machine was off is caught up when it next wakes, not skipped.');
      if (!existsSync(path.join(DEPLOYED ? RUNTIME_DATA : projectDir, 'backup.config.json'))) {
        console.log('  ⚠ Backups are not configured yet - run:  npm run backup -- init');
      }
    }
  }

  if (which !== 'sync') {
    if (!DEPLOYED) writeApiRunner(projectDir);
    console.log(`\n${DEPLOYED ? 'Using protected runner' : 'Wrote'} ${API_RUNNER}`);
    ok = (await create(apiSpec())) && ok;
    if (ok) {
      console.log(`\n✓ "${API_TASK}" starts at logon, hidden, and restarts itself if it dies.`);
      console.log('  The dashboard is then always at http://127.0.0.1:3010');
      console.log('  Start it now without logging out:  npm run api');
    }
  }

  console.log('\n  Check with:  npm run schedule:status');
  console.log('  Remove with: npm run schedule:remove');
  if (!ok) process.exitCode = 1;
}

async function remove(which: Which): Promise<void> {
  const targets = [
    ...(which !== 'api' ? [SYNC_TASK] : []),
    ...(which !== 'sync' ? [API_TASK] : []),
  ];
  let removed = 0;
  for (const taskName of targets) {
    if (!(await query(taskName))) continue;
    try {
      await powershell(`Unregister-ScheduledTask -TaskName ${psQuote(taskName)} -Confirm:$false`);
      console.log(`✓ Removed "${taskName}".`);
      removed++;
    } catch (err) {
      console.error(
        isAccessDenied(err)
          ? `  Could not remove "${taskName}": access denied. Try an elevated terminal.`
          : `  Could not remove "${taskName}": ${err instanceof Error ? err.message.split('\n')[0] : err}`,
      );
      process.exitCode = 1;
    }
  }
  if (removed === 0 && process.exitCode !== 1) console.log('Nothing to remove.');
  if (which !== 'sync') {
    console.log('\nA dashboard already running stays up until you close it or log out.');
  }
}

type Which = 'both' | 'sync' | 'api';

async function main() {
  if (process.platform !== 'win32') {
    console.error('This helper targets Windows Task Scheduler. On Linux/macOS use cron.');
    process.exitCode = 1;
    return;
  }

  const words = process.argv.slice(2);
  const command = words.find((a) => ['status', 'install', 'remove', 'check'].includes(a)) ?? 'status';
  const which: Which = words.includes('sync') ? 'sync' : words.includes('api') ? 'api' : 'both';

  if (command === 'install') await install(which);
  else if (command === 'remove') await remove(which);
  else if (command === 'check') await dryRun(which);
  else await status(which);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exitCode = 1;
});
